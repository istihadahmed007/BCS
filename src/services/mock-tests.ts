export class MockTestService {
  /**
   * Retrieves all mock test definitions filtered by track, stream, or category
   */
  static getMockTests(filter?: {
    track?: ExamTrackId;
    stream?: ProfessionalStreamId;
    category?: MockTestCategory | 'all';
  }): MockTestDefinition[] {
    let list = [...MOCK_TEST_DEFINITIONS];

    if (filter?.track) {
      list = list.filter((t) => t.examTrackId === filter.track);
    }

    if (filter?.stream && filter.stream !== 'general') {
      list = list.filter(
        (t) => t.professionalStream === 'all' || t.professionalStream === filter.stream || t.examTrackId === 'general_bcs'
      );
    }

    if (filter?.category && filter.category !== 'all') {
      list = list.filter((t) => t.category === filter.category);
    }

    return list;
  }

  /**
   * Retrieves a single mock test definition by ID
   */
  static getMockTestById(id: string): MockTestDefinition | undefined {
    return MOCK_TEST_DEFINITIONS.find((t) => t.id === id);
  }

  /**
   * Starts an authenticated exam attempt from a mock test definition
   */
  static startAttempt(definitionId: string, userId: string): TestSession {
    const def = this.getMockTestById(definitionId);
    if (!def) {
      throw new Error(`Mock test definition not found for ID: ${definitionId}`);
    }

    // Map definition category to TestType
    let testType: TestType = 'full_mock';
    if (def.category === 'subject_wise') testType = 'subject_test';
    else if (def.category === 'topic_wise') testType = 'topic_quiz';
    else if (def.category === 'mixed_practice') testType = 'mixed_practice';
    else if (def.category === 'previous_year') testType = 'previous_year';
    else if (def.category === 'special_bcs_health') {
      testType = def.totalQuestions === 200 ? 'full_mock' : 'subject_test';
    }

    return AssessmentEngine.createSession({
      userId,
      examTrackId: def.examTrackId,
      professionalStream: def.professionalStream === 'all' ? 'general' : def.professionalStream,
      testType,
      durationMinutes: def.durationMinutes,
      title: def.titleBn || def.title,
    });
  }
}
