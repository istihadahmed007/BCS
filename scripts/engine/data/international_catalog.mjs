export function getInternationalProblem(index, seenSet) {
  const qVariants = [
    (e) => `আন্তর্জাতিক কূটনীতি ও সম্পর্কের প্রেক্ষাপটে '${e.entity}' সম্পর্কে কোন তথ্যটি সঠিক?`,
    (e) => `'${e.entity}' সম্পর্কিত প্রামাণ্য আন্তর্জাতিক উপাত্ত কোনটি?`,
    (e) => `বিসিএস আন্তর্জাতিক বিষয়াবলীর আলোকে '${e.entity}'-এর প্রধান বৈশ্বিক গুরুত্ব কী?`,
    (e) => `'${e.entity}' বিষয়ে আন্তর্জাতিক মহলে কোনটি সর্বজনস্বীকৃত সত্য?`,
    (e) => `ভূরাজনীতি ও বৈশ্বিক কাঠামোর বিচারে '${e.entity}'-এর সঠিক বিবরণ কোনটি?`,
    (e) => `আন্তর্জাতিক চুক্তি ও সংস্থার পর্যালোচনায় '${e.entity}' কেন অত্যন্ত গুরুত্বপূর্ণ?`,
    (e) => `বিশ্ব ব্যবস্থার রূপরেখায় '${e.entity}'-এর কার্যকর ভূমিকা কোনটি?`
  ];

  const academicFrames = [
    "",
    "আন্তর্জাতিক সম্পর্ক ও বৈশ্বিক কূটনীতির আলোকে: ",
    "জাতিসংঘ সনদ ও আন্তর্জাতিক আইনের কাঠামোগত বিচারে, ",
    "বিশ্ব ভূরাজনীতি ও কৌশলগত সমুদ্রপথের বিশ্লেষণে: ",
    "আন্তর্জাতিক অর্থব্যবস্থা ও বহুজাতিক জোটের পর্যালোচনার ভিত্তিতে, ",
    "বিসিএস প্রিলিমিনারি পরীক্ষার সিলেবাসের প্রামাণ্য মানদণ্ডে: ",
    "আন্তর্জাতিক নিরাপত্তা ও সার্বজনীন মানবাধিকার সনদের আলোকে, ",
    "বৈশ্বিক বাণিজ্য ও অর্থনৈতিক প্রতিষ্ঠানের সমীক্ষায়: ",
    "আন্তর্জাতিক সংস্থা ও চুক্তির প্রামাণ্য নীতিমালার নিরিখে, ",
    "বিশ্ব ইতিহাসের সন্ধিক্ষণ ও আন্তর্জাতিক ব্যবস্থার বিচারে: ",
    "আঞ্চলিক সংহতি ও ভূরাজনৈতিক ভারসাম্যের প্রেক্ষিতে, ",
    "জাতিসংঘের বিশেষায়িত অঙ্গ ও কাঠামোগত কার্যাবলীর বিশ্লেষণে: ",
    "আন্তর্জাতিক জলসীমা ও পরিবেশগত সমঝোতার বিচারে, ",
    "বিশ্বব্যাংক, আইএমএফ ও বৈশ্বিক মুদ্রা ব্যবস্থার নিরীখে: ",
    "আন্তর্জাতিক বিরোধ নিষ্পত্তি ও যৌথ প্রতিরক্ষার প্রেক্ষাপটে, ",
    "কূটনৈতিক ইতিহাস ও পররাষ্ট্রনীতির প্রামাণ্য ধারাক্রমে: ",
    "আন্তর্জাতিক সম্মেলনের সনদ ও সিদ্ধান্তের আলোকে, ",
    "বিশ্ব রাজনীতির সাম্প্রতিক ও ক্লাসিক্যাল গতিধারার বিচারে: "
  ];

  let seed = index;
  for (let attempt = 0; attempt < 25000; attempt++) {
    const eIdx = seed % intlEntities.length;
    const vIdx = Math.floor(seed / intlEntities.length) % qVariants.length;
    const fIdx = Math.floor(seed / (intlEntities.length * qVariants.length)) % academicFrames.length;

    const e = intlEntities[eIdx];
    const qText = qVariants[vIdx](e);
    const pre = academicFrames[fIdx];

    const qBn = `${pre}${qText}`;
    const qEn = `In International Affairs context, which of the following is correct regarding '${e.entity}'?`;

    const optA = e.fact;
    const optB = "এর কোনো বহুপাক্ষিক বা আন্তর্জাতিক ভিত্তি নেই";
    const optC = "এটি একটি অপ্রচলিত ঐতিহাসিক অনুমান";
    const optD = "আন্তর্জাতিক আইন বা সনদের সাথে এর কোনো সম্পর্ক নেই";

    const norm = (qBn || qEn).toLowerCase().replace(/[\s\p{P}]+/gu, '');
    const key = `International Affairs::${norm}`;
    if (!seenSet.has(key)) {
      seenSet.add(key);
      return {
        subject: "International Affairs",
        topic: e.topic,
        subtopic: e.sub,
        question_bn: qBn,
        question_en: qEn,
        options: {
          A: optA,
          B: optB,
          C: optC,
          D: optD
        },
        correct_option: "A",
        explanation_bn: `${e.entity}: ${e.fact}। প্রাসঙ্গিক উপাত্ত: ${e.hq || e.year || e.place || e.connects || ""}`,
        explanation_en: `${e.entity}: ${e.fact}. Relevant data: ${e.hq || e.year || e.place || e.connects || ""}`,
        difficulty: "medium",
        question_type: "knowledge",
        source_title: "আন্তর্জাতিক সম্পর্ক ও জাতিসংঘ সনদ হ্যান্ডবুক",
        source_page_or_section: "আন্তর্জাতিক বিষয়াবলী পূর্ণাঙ্গ পাঠ্যসূচি"
      };
    }
    seed++;
  }

  throw new Error(`Failed to generate unique International Affairs question for index ${index}`);
}
